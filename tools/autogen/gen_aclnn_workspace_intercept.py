#!/usr/bin/env python3

import argparse
from pathlib import Path
import re


FUNC_RE = re.compile(
    r"(?:[A-Z_][A-Z0-9_]*\s+|__attribute__\s*\(\([^;]*?\)\)\s+)*"
    r"aclnnStatus\s+"
    r"(acl[A-Za-z0-9_]+GetWorkspaceSize)\s*"
    r"\((.*?)\)\s*;",
    re.S,
)


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//.*", "", text)


def split_top_level(text: str) -> list[str]:
    parts: list[str] = []
    current: list[str] = []
    depths = {"(": 0, "[": 0, "{": 0}
    closing = {")": "(", "]": "[", "}": "{"}
    for ch in text:
        if ch in depths:
            depths[ch] += 1
        elif ch in closing:
            depths[closing[ch]] -= 1
        elif ch == "," and not any(depths.values()):
            part = "".join(current).strip()
            if part:
                parts.append(part)
            current = []
            continue
        current.append(ch)
    tail = "".join(current).strip()
    if tail:
        parts.append(tail)
    return parts


def normalize(text: str) -> str:
    return " ".join(text.strip().split())


def extract_name_and_type(param: str) -> tuple[str, str]:
    param = normalize(param)
    idx = len(param) - 1
    bracket_depth = 0
    while idx >= 0:
        ch = param[idx]
        if ch == "]":
            bracket_depth += 1
        elif ch == "[":
            bracket_depth -= 1
        elif bracket_depth == 0 and (ch.isalnum() or ch == "_"):
            break
        idx -= 1
    if idx < 0:
        raise ValueError(f"cannot parse parameter name: {param}")

    end = idx
    while idx >= 0 and (param[idx].isalnum() or param[idx] == "_"):
        idx -= 1
    name = param[idx + 1:end + 1]
    type_part = (param[:idx + 1] + param[end + 1:]).strip()
    type_part = re.sub(r"\s+([\[\]])", r"\1", type_part)
    return name, normalize(type_part)


def compact_type(type_part: str) -> str:
    return re.sub(r"\s+", "", type_part).replace("const", "")


def parse_functions(header: Path, minimum: int = 100) -> list[dict]:
    text = strip_comments(header.read_text(encoding="utf-8", errors="ignore"))
    functions: list[dict] = []
    for match in FUNC_RE.finditer(text):
        params = []
        for raw_param in split_top_level(normalize(match.group(2))):
            name, type_part = extract_name_and_type(raw_param)
            params.append({
                "decl": normalize(raw_param),
                "name": name,
                "type": type_part,
                "is_memory_resource": compact_type(type_part) in {
                    "aclTensor*", "aclTensorList*", "aclScalar*", "aclScalarList*",
                    "aclIntArray*", "aclFloatArray*", "aclBoolArray*"
                },
            })

        if len(params) < 2:
            raise ValueError(f"{match.group(1)} is missing workspace/executor outputs")
        if compact_type(params[-2]["type"]) != "uint64_t*":
            raise ValueError(f"unexpected workspace output in {match.group(1)}")
        if compact_type(params[-1]["type"]) != "aclOpExecutor**":
            raise ValueError(f"unexpected executor output in {match.group(1)}")

        functions.append({
            "name": match.group(1),
            "params": params,
            "params_sig": ", ".join(param["decl"] for param in params),
            "types_sig": ", ".join(param["type"] for param in params),
            "args_sig": ", ".join(param["name"] for param in params),
            "executor": params[-1]["name"],
            "resources": [param["name"] for param in params if param["is_memory_resource"]],
        })

    if len(functions) < minimum:
        raise ValueError(f"parsed only {len(functions)} ACLNN workspace functions")
    return functions


def emit_source(functions: list[dict]) -> str:
    lines = [
        "// Auto-generated by tools/autogen/gen_aclnn_workspace_intercept.py.",
        "// Do not edit directly.",
        "",
        '#include "xsched/ascend/shim/shim.h"',
        '#include "xsched/utils/function.h"',
        '#include "xsched/utils/symbol.h"',
        "",
        "#include <dlfcn.h>",
        "#include <cstdio>",
        "#include <cstdlib>",
        "",
        "using namespace xsched::ascend;",
        "",
    ]
    for fn in functions:
        lines.extend([
            "",
            f"EXPORT_C_FUNC aclnnStatus {fn['name']}({fn['params_sig']})",
            "{",
            f"    using Func = aclnnStatus (*)({fn['types_sig']});",
            f"    static const auto func = reinterpret_cast<Func>(ResolveOriginalAclnn(\"{fn['name']}\"));",
            "    if (func == nullptr) return ACL_ERROR_RT_FEATURE_NOT_SUPPORT;",
            "    const bool nested = InNativeCall();",
            "    aclnnStatus ret;",
            f"    {{ NativeCallScope native; ret = func({fn['args_sig']}); }}",
        ])
        if fn["resources"]:
            resources = ", ".join(fn["resources"])
            lines.extend([
                "    if (ret == ACL_SUCCESS && !nested) {",
                f"        const void *resources[] = {{{resources}}};",
                f"        XRecordAclNNWorkspace({fn['executor']}, resources, {len(fn['resources'])});",
                "    }",
            ])
        else:
            lines.extend([
                "    if (ret == ACL_SUCCESS && !nested) {",
                f"        XRecordAclNNWorkspace({fn['executor']}, nullptr, 0);",
                "    }",
            ])
        lines.extend(["    return ret;", "}"])
    for fn in functions:
        if not fn.get("new_execute"): continue
        api = fn["name"].removesuffix("GetWorkspaceSize")
        lines.extend([
            f'EXPORT_C_FUNC aclnnStatus {api}(void *workspace, uint64_t bytes, aclOpExecutor *executor, aclrtStream stream)',
            '{',
            f'    auto native = reinterpret_cast<AclNNExecuteFunc>(ResolveOriginalAclnn("{api}"));',
            '    if (!native) return ACL_ERROR_RT_FEATURE_NOT_SUPPORT;',
            f'    return XnnSubmit("{api}", workspace, bytes, executor, stream, native);',
            '}',
        ])
    lines.append("")
    return "\n".join(lines)


def emit_dlsym(functions: list[dict]) -> str:
    lines = [
        "// Auto-generated by tools/autogen/gen_aclnn_workspace_intercept.py.",
        "// Do not edit directly.",
        "",
    ]
    lines.extend(f'    {{"{fn["name"]}", nullptr}},' for fn in functions)
    lines.extend(f'    {{"{fn["name"].removesuffix("GetWorkspaceSize")}", nullptr}},' for fn in functions if fn.get("new_execute"))
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--extra-header-dir", type=Path)
    parser.add_argument("--existing-intercepts", type=Path)
    parser.add_argument("--source-output", type=Path, required=True)
    parser.add_argument("--dlsym-output", type=Path, required=True)
    args = parser.parse_args()

    functions = parse_functions(args.header)
    seen = {fn["name"] for fn in functions}
    existing = set(re.findall(r"\baclnn\w+\b", args.existing_intercepts.read_text())) if args.existing_intercepts else set()
    if args.extra_header_dir:
        for header in sorted(args.extra_header_dir.glob("*.h")):
            for fn in parse_functions(header, minimum=0):
                if fn["name"] in seen: continue
                seen.add(fn["name"])
                fn["new_execute"] = fn["name"].removesuffix("GetWorkspaceSize") not in existing
                functions.append(fn)
    args.source_output.parent.mkdir(parents=True, exist_ok=True)
    args.dlsym_output.parent.mkdir(parents=True, exist_ok=True)
    args.source_output.write_text(emit_source(functions), encoding="utf-8")
    args.dlsym_output.write_text(emit_dlsym(functions), encoding="utf-8")
    print(f"Generated {len(functions)} ACLNN workspace interceptors")


if __name__ == "__main__":
    main()
